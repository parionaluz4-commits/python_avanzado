# crear un programa que me permita
# desarrollar las 4 operaciones basica
# (suma, resta, division, multiplicacion)
def suma(a, b):
    return a + b

def resta(a, b):
    return a - b

def multiplicacion(a, b):
    return a * b

def division(a, b):
    return a / b

# probando
print("Suma:", suma(10, 2))
print("Resta:", resta(10, 2))
print("Multiplicacion:", multiplicacion(10, 2))
print("Division:", division(10, 2))